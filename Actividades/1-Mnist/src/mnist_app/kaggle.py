"""Send a training run to Kaggle.

The repository travels as a private dataset mounted at /kaggle/input/mnist-repo
(including mnist.npz), so the kernel runs the same code as the local trainer
with internet disabled. Only a generated launcher is uploaded as the code file;
each model gets its own kernel.
"""

from __future__ import annotations

import hashlib
import json
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

from mnist_app.model import MODEL_FILES, project_root

DATASET_SLUG = "mnist-repo"
DATASET_TITLE = "MNIST repo"
DATASET_LICENSE = "CC0-1.0"
KAGGLE_INPUT = "/kaggle/input/mnist-repo"
BUILD_DIR = "build/kaggle"
POLL_SECONDS = 20
TIMEOUT_SECONDS = 2 * 60 * 60

LAUNCHER = '''"""Generated by `mnist-train --where kaggle`: runs the dataset code on Kaggle."""

import sys
import zipfile
from pathlib import Path

MOUNT = Path("/kaggle/input/mnist-repo")
REPO = MOUNT if (MOUNT / "src" / "mnist_app").is_dir() else Path("/kaggle/temp/mnist-repo")

if not (REPO / "src" / "mnist_app").is_dir():
    # Kaggle usually unzips the uploaded archive into the mount; if it arrived
    # as a zip instead, extract it once into the ephemeral working area.
    REPO.mkdir(parents=True, exist_ok=True)
    archive = MOUNT / "repo.zip"
    if not archive.is_file():
        print("unexpected /kaggle/input layout:", sorted(p.name for p in MOUNT.iterdir()))
        raise SystemExit("repo not found at " + str(MOUNT))
    with zipfile.ZipFile(archive) as handle:
        handle.extractall(REPO)

sys.path.insert(0, str(REPO / "src"))

from mnist_app.train import run

run(
    "{model}",
    epochs={epochs},
    batch_size={batch_size},
    seed={seed},
    mnist_npz=REPO / "data" / "mnist.npz",
)
'''


class KaggleError(RuntimeError):
    """A Kaggle CLI step failed."""


def launcher(model: str, epochs: int, batch_size: int, seed: int) -> str:
    """Code file uploaded to Kaggle; it imports the repo from the dataset."""
    return LAUNCHER.format(
        input=KAGGLE_INPUT,
        model=model,
        epochs=epochs,
        batch_size=batch_size,
        seed=seed,
    )


def dataset_id(owner: str) -> str:
    """Owner-scoped dataset id, so the account stays out of the source."""
    return f"{owner}/{DATASET_SLUG}"


def kernel_metadata(model: str, username: str) -> dict:
    """kernel-metadata.json for one model's kernel."""
    slug = f"mnist-{model}-training"
    return {
        "id": f"{username}/{slug}",
        "title": f"MNIST {model} training",
        "code_file": "code.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": False,
        "dataset_sources": [dataset_id(username)],
        "competition_sources": [],
        "kernel_sources": [],
    }


def kaggle(*args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    """Run the Kaggle CLI, raising with its output when it fails."""
    binary = shutil.which("kaggle")
    if binary is None:
        raise KaggleError("Kaggle CLI not found. Install it: uv tool install --with six kaggle")
    result = subprocess.run([binary, *args], text=True, capture_output=True)
    if check and result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        raise KaggleError(f"kaggle {' '.join(args)} failed:\n{detail}")
    return result


def username() -> str:
    for line in kaggle("config", "view").stdout.splitlines():
        if line.strip().startswith("- username:"):
            return line.split(":", 1)[1].strip()
    raise KaggleError("No active account in the Kaggle CLI; run `kaggle auth login`.")


def tree_hash(folder: Path) -> str:
    """Content hash of the dataset staging, to skip unchanged uploads."""
    digest = hashlib.sha256()
    for path in sorted(p for p in folder.rglob("*") if p.is_file()):
        digest.update(str(path.relative_to(folder)).encode())
        digest.update(path.read_bytes())
    return digest.hexdigest()


def stage_dataset(owner: str) -> tuple[Path, str]:
    """Zip src/ + mnist.npz into the dataset staging (one uploaded file)."""
    root = project_root()
    build = root / BUILD_DIR
    payload = build / "payload"
    staging = build / "dataset"
    for folder in (payload, staging):
        if folder.exists():
            shutil.rmtree(folder)

    shutil.copytree(root / "src", payload / "src", ignore=shutil.ignore_patterns("__pycache__"))

    npz = Path.home() / ".keras" / "datasets" / "mnist.npz"
    if not npz.is_file():
        raise KaggleError(
            "Missing ~/.keras/datasets/mnist.npz. Run `uv run mnist-train --model dense` "
            "once so MNIST is cached and can travel with the dataset."
        )
    (payload / "data").mkdir(parents=True)
    shutil.copy2(npz, payload / "data" / "mnist.npz")

    staging.mkdir(parents=True)
    shutil.make_archive(str(staging / "repo"), "zip", root_dir=payload)

    metadata = {"title": DATASET_TITLE, "id": dataset_id(owner), "licenses": [{"name": DATASET_LICENSE}]}
    (staging / "dataset-metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    return staging, tree_hash(payload)


def sync_dataset(staging: Path, digest: str, dataset: str) -> None:
    """Create the dataset once, then upload a version only when code or data change."""
    marker = staging.parent / ".dataset-hash"
    if marker.is_file() and marker.read_text().strip() == digest:
        print("Dataset unchanged; reusing the current version.")
        return

    exists = kaggle("datasets", "files", dataset, check=False).returncode == 0
    if exists:
        print("Uploading a new dataset version...")
        kaggle("datasets", "version", "-p", str(staging), "-m", f"sync {digest[:8]}")
    else:
        print("Creating the private dataset...")
        kaggle("datasets", "create", "-p", str(staging))
    marker.write_text(digest + "\n")


def stage_kernel(model: str, epochs: int, batch_size: int, seed: int, owner: str) -> Path:
    """Write the generated launcher and its metadata under build/kaggle/."""
    staging = project_root() / BUILD_DIR / f"kernel-{model}"
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)
    (staging / "code.py").write_text(launcher(model, epochs, batch_size, seed))
    (staging / "kernel-metadata.json").write_text(
        json.dumps(kernel_metadata(model, owner), indent=2) + "\n"
    )
    return staging


def wait(ref: str) -> str:
    """Poll the kernel until it reaches a terminal status."""
    deadline = time.monotonic() + TIMEOUT_SECONDS
    last = None
    while time.monotonic() < deadline:
        result = kaggle("kernels", "status", ref, check=False)
        output = (result.stdout or result.stderr).strip()
        match = re.search(r'status "([^"]+)"', output)
        status = match.group(1) if match else None
        if status is None:
            print(f"  status unavailable ({output.splitlines()[-1] if output else 'no output'}); retrying")
        elif status != last:
            print(f"  {status}")
            last = status
        if status and status.endswith(("COMPLETE", "ERROR", "CANCELED", "CANCEL_REQUESTED")):
            return status
        time.sleep(POLL_SECONDS)
    raise KaggleError("Kaggle run did not finish in time.")


def download(ref: str) -> None:
    """Fetch /kaggle/working into models/, dropping the run log."""
    models = project_root() / "models"
    kaggle("kernels", "output", ref, "-p", str(models))
    log = models / f"{ref.split('/', 1)[1]}.log"
    if log.is_file():
        log.unlink()


def train_remote(
    model: str,
    epochs: int = 30,
    batch_size: int = 32,
    seed: int = 0,
    wait_for_run: bool = True,
) -> int:
    """Stage the dataset, push the kernel, wait and download the artifact."""
    try:
        owner = username()
        ref = f"{owner}/mnist-{model}-training"

        staging, digest = stage_dataset(owner)
        sync_dataset(staging, digest, dataset_id(owner))

        kernel = stage_kernel(model, epochs, batch_size, seed, owner)
        print(f"Pushing {ref} ...")
        kaggle("kernels", "push", "-p", str(kernel))
        print(f"  https://www.kaggle.com/code/{ref}")

        if not wait_for_run:
            print(f"Follow it with: kaggle kernels status {ref}")
            print(f"Download it with: kaggle kernels output {ref} -p models")
            return 0

        status = wait(ref)
        if not status.endswith("COMPLETE"):
            log = kaggle("kernels", "logs", ref, check=False)
            print((log.stdout or log.stderr)[-4000:])
            raise KaggleError(f"Kaggle finished with {status}.")

        download(ref)
        print(f"Artifacts downloaded to {project_root() / 'models'}")
        return 0
    except KaggleError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
